import unittest
from pathlib import Path


class TemporaryCiFailureCheck(unittest.TestCase):
    def test_leaves_an_ignored_file(self):
        path = Path(__file__).resolve().parents[1] / 'tmp' / 'ci-generated.txt'
        path.parent.mkdir(exist_ok=True)
        path.write_text('generated by a temporary test\n')
